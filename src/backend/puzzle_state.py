_THREAD_LOCK = threading.RLock()
_LOCK_STATE = threading.local()

class StateSaveError(OSError):
    """Raised when the game state could not be written to disk."""

def _rolls_back_on_save_failure(method):
    """
    Restore the in-memory engine to its pre-call state when the call's save fails,
    so a request that could not be persisted leaves no trace.
    """
    @functools.wraps(method)
    def wrapper(self, *args, **kwargs):
        snapshot = copy.deepcopy(self.to_dict())
        try:
            return method(self, *args, **kwargs)
        except StateSaveError:
            self.from_dict(snapshot)
            raise
    return wrapper

