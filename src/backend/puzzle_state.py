    @_rolls_back_on_save_failure
    def judge_ritual(self, phrase: str, deliver_to_workbook: bool = False) -> Dict[str, Any]:
        """
        deliver_to_workbook: for callers that are not the workbook itself (the MCP agent). A successful ritual then
        also queues its concluding actions, which the workbook receives on its next /api/pending heartbeat.
        """
        if self.archive_sealed:
            return {
                "accepted": False,
                "banished": False,
                "current_phase": self.phase_number,
                "message": "The archive is sealed. The void books are closed."
            }

        phrase_clean = re.sub(r"\s+", " ", str(phrase)[:500].strip().upper())
        # Spec-compliant ritual sealing: requires MIDNIGHT_SETTLEMENT phase and exact phrase
        if self.current_phase == PhaseEnum.MIDNIGHT_SETTLEMENT and phrase_clean == "SEAL THE DEEP VAULT":
            self.archive_sealed = True
            res = {
                "accepted": True,
                "banished": True,
                "current_phase": self.phase_number,
                "stamp": "[ ARCHIVE SEALED - OCTOBER 31, 1928 - 00:01 AM ]",
                "message": "THE ENTRY IS BALANCED. CLOCK OUT AND NEVER RETURN.",
                "actions": [
                    {
                        "command": "TRIGGER_FX",
                        "effect": "THUNDER_STROBE"
                    },
                    {
                        "command": "TRIGGER_FX",
                        "effect": "SCREEN_TREMOR"
                    },
                    {
                        "command": "LOCK_SHEET"
                    }
                ]
            }
            if deliver_to_workbook:
                # Same save as the seal itself, so the archive can never be sealed without the workbook being told
                for action in res["actions"]:
                    if len(self.pending_effects) >= 50:
                        self.pending_effects.pop(0)
                    self.pending_effects.append(dict(action))
            self.save_state()
            return res
        else:
            res = {
                "accepted": False,
                "banished": False,
                "current_phase": self.phase_number,
                "message": "MISMATCHED DEBIT. YOUR RITUAL VOID ACCRUES BLOOD DEBT.",
                "actions": [
                    {
                        "command": "TRIGGER_FX",
                        "effect": "THUD_BEEP"
                    }
                ]
            }
            return res

    @_rolls_back_on_save_failure
    def queue_haunt(self, haunt_type: str, target_cell: Optional[str] = None, message: Optional[str] = None):
        clean_haunt = str(haunt_type).strip().lower()
        if clean_haunt not in VALID_HAUNT_TYPES:
            raise ValueError(f"Invalid haunt type: {haunt_type}")
        if target_cell:
            target_cell = validate_haunt_target(target_cell, clean_haunt)
        clean_msg = str(message)[:2000] if message is not None else None
        with file_lock():
            self.load_state()
            if len(self.pending_effects) >= 50:
                self.pending_effects.pop(0)
            self.pending_effects.append({
                "type": clean_haunt,
                "target_cell": target_cell,
                "message": clean_msg
            })
            self.save_state()

    @_rolls_back_on_save_failure
    def pop_pending_effects(self) -> List[Dict[str, Any]]:
        with file_lock():
            self.load_state()
            if not self.pending_effects:
                # The VBA client polls every 3 seconds; an empty queue must not touch the disk
                return []
            effects = list(self.pending_effects)
            self.pending_effects.clear()
            self.save_state()
            return effects
